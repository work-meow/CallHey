"use client";

/**
 * Один AudioContext на вкладку.
 *
 * Каждый новый контекст открывает аудиоустройство — это дорого, и Chrome
 * держит жесткий предел в шесть штук на страницу. Потребителей здесь два:
 * микрофонный тракт и детектор речи, причем второй пересобирает свой граф
 * при каждом изменении состава комнаты. С контекстом на каждую пересборку
 * восьмером этот предел выбирается за один звонок, и графы перестают
 * создаваться совсем.
 *
 * Поэтому контекст создается один раз и не закрывается — потребители
 * отсоединяют свои узлы сами. Между звонками он засыпает.
 */
let shared: AudioContext | null = null;

export function audioContext() {
  shared ??= new AudioContext();
  // До первого жеста пользователя браузер держит контекст приостановленным.
  if (shared.state === "suspended") void shared.resume();
  return shared;
}

/** Усыпляет контекст после звонка: узлов не осталось, держать устройство незачем. */
export function idleAudio() {
  if (shared?.state === "running") void shared.suspend();
}
